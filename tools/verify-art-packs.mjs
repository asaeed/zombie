  assert.ok(box.x>=0&&box.x+box.width<=390);
  await page.screenshot({path:evidence+'/menu-mobile.png'});report.game.mobileSelectorFits=true;
  assert.deepEqual(errors,[]);
  report.browserErrors=errors;report.simulated503Errors=expectedNetworkErrors.length;
  await fs.writeFile(evidence+'/validation.json',JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report,null,2));
