  report.review.boards=await page.locator('.board img').evaluateAll(images=>images.map(image=>({src:image.getAttribute('src'),width:image.naturalWidth,height:image.naturalHeight})));
  assert.equal(report.review.boards.length,expectedCount);
  assert.equal(expectedCount,12);
  assert.deepEqual(directionData.directions.filter(direction=>direction.theme==='dark').map(direction=>direction.letter),['I','J']);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:evidence+'/gallery-desktop.png',fullPage:true});
  await page.locator('.board').first().click();await assert.ok(await page.locator('#detail').evaluate(dialog=>dialog.open));
  await page.screenshot({path:evidence+'/detail-desktop.png'});await page.locator('#close-detail').click();
  await page.getByText('Compare',{exact:true}).click();
  await page.selectOption('#choice-a','paper-siege');await page.selectOption('#choice-b','woodcut-alarm');
  await page.waitForFunction(()=>document.querySelector('#image-a').complete&&document.querySelector('#image-b').complete);
  assert.match(await page.locator('#name-a').innerText(),/Paper Siege/);
  await page.screenshot({path:evidence+'/compare-desktop.png'});
  await page.selectOption('#zoom','100');
  assert.equal(await page.locator('#image-a').evaluate(image=>image.clientWidth===image.naturalWidth),true);
  await page.selectOption('#zoom','150');
  assert.equal(await page.locator('#image-b').evaluate(image=>image.clientWidth===image.naturalWidth*1.5),true);
  await page.selectOption('#zoom','fit');
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:evidence+'/compare-mobile.png',fullPage:true});
  await page.getByText('Gallery',{exact:true}).click();await page.screenshot({path:evidence+'/gallery-mobile.png',fullPage:true});
  await page.locator('.board').last().click();
  assert.equal(await page.locator('#detail').evaluate(dialog=>dialog.getBoundingClientRect().right<=innerWidth),true);
  await page.screenshot({path:evidence+'/detail-mobile.png'});await page.keyboard.press('Escape');
  report.review.responsive=true;report.review.comparison=true;report.review.zoom=true;

  await page.setViewportSize({width:1440,height:900});
  await page.goto('http://127.0.0.1:8787/?artPack=sculpted');
  await page.waitForFunction(()=>window._game&&SCULPTED_WORLD.ready&&ART_PACK_STATE.active==='sculpted');
  const selected=await page.evaluate(()=>{const u=_game.units[0];u.selected=true;u.carrying=13;_game.selected=[u];return u.id;});
  const menu=await page.evaluate(()=>mainMenuButtonRect(innerWidth));await page.mouse.click(menu.x+menu.w/2,menu.y+menu.h/2);
  await page.waitForFunction(()=>_input.menuOpen&&_game.paused&&!document.getElementById('graphics-setting').hidden);
  const before=await page.evaluate(snapshot);
  const time=await page.evaluate(()=>_game.gameTime);await page.waitForTimeout(250);
  assert.equal(await page.evaluate(()=>_game.gameTime),time);
  const shaderCount=await page.evaluate(()=>SCULPTED_WORLD.characters.size);assert.equal(shaderCount,18);
  await page.screenshot({path:evidence+'/menu-sculpted.png'});
  await page.selectOption('#graphics-pack','classic');await page.waitForFunction(()=>ART_PACK_STATE.active==='classic');
  assert.equal(await page.evaluate(snapshot),before);
  assert.equal(await page.evaluate(()=>!SCULPTED_WORLD.ready&&!sculptedActor('soldier')&&!sculptedObject('hq')&&!sculptedTerrainFrame(0,0,0)),true);
  await page.screenshot({path:evidence+'/menu-classic.png'});
