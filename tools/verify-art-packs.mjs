  assert.ok(fill>10000);
  await page.evaluate(()=>{_saveGameNow();_input.setMenuOpen(false);});
  await page.reload();await page.waitForFunction(()=>SCULPTED_WORLD.ready&&window._game);
  assert.equal(await page.evaluate(()=>_game.selected[0]?.id),selected);
  assert.equal(await page.evaluate(()=>_game.selected[0]?.carrying),13);
  const again=await page.evaluate(()=>mainMenuButtonRect(innerWidth));await page.mouse.click(again.x+again.w/2,again.y+again.h/2);
  await page.selectOption('#graphics-pack','classic');await page.waitForFunction(()=>ART_PACK_STATE.active==='classic');
  await page.goto('http://127.0.0.1:8787/');await page.waitForFunction(()=>ART_PACK_STATE.active==='classic'&&window._game);
  assert.equal(await page.evaluate(()=>localStorage.getItem(ART_PACK_STORAGE_KEY)),'classic');
